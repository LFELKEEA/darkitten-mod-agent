def _id_expr(mc: str, name: str = "name", modid: str = "MOD_ID") -> str:
    if mc.startswith("26."):
        return f'Identifier.fromNamespaceAndPath({modid}, {name})'
    if _key(mc) >= (1, 21, 0):
        return f'ResourceLocation.fromNamespaceAndPath({modid}, {name})'
    return f'new ResourceLocation({modid}, {name})'


def _attributes_class(profile, entity: EntityPlan) -> str:
    base = "Monster.createMonsterAttributes()" if entity.kind in {"hostile", "boss"} else "Mob.createMobAttributes()"
    return (
        f"    public static AttributeSupplier.Builder createAttributes() {{\n"
        f"        return {base}.add(Attributes.MAX_HEALTH, {entity.health:.1f}D)"
        f".add(Attributes.MOVEMENT_SPEED, {entity.speed:.3f}D)"
        f".add(Attributes.ATTACK_DAMAGE, {max(0.0, entity.attack):.1f}D)"
        f".add(Attributes.FOLLOW_RANGE, 32.0D);\n"
        f"    }}\n"
    )


