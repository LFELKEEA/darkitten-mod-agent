"""Advanced Java systems: entities, NPCs, bosses, block entities, menus.

Simple mods only need blocks and items. Twilight-Forest / MCA scale mods need
entities that spawn, bosses with bars and phases, machines with inventories,
and screens. Those are loader APIs, so this module emits a small, conservative
set of classes per loader instead of pretending one source file works
everywhere.

Design constraints:

* Minecraft 1.20.1 (Forge), 1.21.1 (NeoForge/Fabric) are the verified targets.
* 1.21.2+ / 26.x skip advanced Java with a manifest note rather than emitting
  code whose signatures changed. The data layer (worldgen/social) still works.
* Entities are rendered with vanilla ``HumanoidModel`` + a generated skin, so
  a visible, walkable NPC exists on day one without GeckoLib or custom models.
* Machines use a plain 27-slot container and the vanilla dispenser texture, so
  there is no missing GUI texture and no custom networking.
"""
