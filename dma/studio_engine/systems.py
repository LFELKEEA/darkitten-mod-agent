def _mod_fluids(package: str, plan: ContentPlan, profile, loader: str) -> str:
    if not plan.fluids or loader not in {"forge", "neoforge"}:
        return ""
    entries = [(_path(n["id"]), _field(n["id"])) for n in plan.fluids]
    lines = [
        "package " + package + ";",
        "",
        "import net.minecraft.world.level.material.Fluid;",
        "import net.minecraft.world.level.material.FlowingFluid;",
    ]
    if loader == "neoforge":
        lines += [
            "import net.neoforged.neoforge.fluids.BaseFlowingFluid;",
            "import net.neoforged.neoforge.fluids.FluidType;",
            "import net.neoforged.neoforge.registries.DeferredHolder;",
            "import net.neoforged.neoforge.registries.DeferredRegister;",
            "import net.neoforged.neoforge.registries.NeoForgeRegistries;",
            "import net.minecraft.core.registries.Registries;",
            "import net.neoforged.bus.api.IEventBus;",
        ]
    else:
        lines += [
            "import net.minecraftforge.fluids.ForgeFlowingFluid;",
            "import net.minecraftforge.fluids.FluidType;",
            "import net.minecraftforge.registries.DeferredRegister;",
            "import net.minecraftforge.registries.ForgeRegistries;",
            "import net.minecraftforge.registries.RegistryObject;",
            "import net.minecraftforge.eventbus.api.IEventBus;",
        ]
    lines += ["", "public final class ModFluids {"]
    if loader == "neoforge":
        lines += [
            "    public static final DeferredRegister<FluidType> FLUID_TYPES =",
            "        DeferredRegister.create(NeoForgeRegistries.Keys.FLUID_TYPES, ModRegistry.MOD_ID);",
            "    public static final DeferredRegister<Fluid> FLUIDS =",
            "        DeferredRegister.create(Registries.FLUID, ModRegistry.MOD_ID);",
        ]
    else:
        lines += [
            "    public static final DeferredRegister<FluidType> FLUID_TYPES =",
            "        DeferredRegister.create(ForgeRegistries.Keys.FLUID_TYPES, ModRegistry.MOD_ID);",
            "    public static final DeferredRegister<Fluid> FLUIDS =",
            "        DeferredRegister.create(ForgeRegistries.FLUIDS, ModRegistry.MOD_ID);",
        ]
    for name, field in entries:
        lines.append(
            f'    public static final {"DeferredHolder<FluidType, FluidType>" if loader == "neoforge" else "RegistryObject<FluidType>"} '
            f'{field}_TYPE = FLUID_TYPES.register("{name}", () -> new FluidType('
            f'FluidType.Properties.create().density(1200).viscosity(1400).temperature(280)));'
        )
    for name, field in entries:
        ref = ("DeferredHolder<Fluid, BaseFlowingFluid.Source>" if loader == "neoforge"
               else "RegistryObject<FlowingFluid>")
        base = "BaseFlowingFluid" if loader == "neoforge" else "ForgeFlowingFluid"
