def block_expr(node: dict[str, Any], loader: str = "") -> str | None:
    nid = _path(node["id"])
    if node["type"] == "machine":
        return "new SimpleMachineBlock(PROPS)"
    if node["type"] == "energy":
        return "new EnergyCableBlock(PROPS)"
    if node["type"] == "block" and nid.endswith("board"):
        return "new QuestBoardBlock(PROPS)"
    return None


