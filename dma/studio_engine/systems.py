ENTITY_NODE_TYPES = {"entity", "boss", "npc"}


def _key(mc: str) -> tuple[int, int, int]:
    if mc.startswith("26."):
        return (26, 0, 0)
    parts = tuple(int(x) for x in re.findall(r"\d+", mc)[:3])
    return parts + (0,) * (3 - len(parts))


def _class(node_id: str) -> str:
    name = node_id.split(":", 1)[-1]
    parts = [p for p in re.split(r"[^A-Za-z0-9]+", name) if p]
    return "".join(p[:1].upper() + p[1:] for p in parts) or "Entry"


def _path(node_id: str) -> str:
    return node_id.split(":", 1)[-1]


def _field(node_id: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "_", _path(node_id)).strip("_").upper() or "ENTRY"


def _ver_key(mc: str) -> tuple[int, int, int]:
    return _key(mc)


@dataclass
class EntityPlan:
    node: dict[str, Any]
    cls: str
    field: str
    kind: str            # npc | passive | hostile | boss
    texture: str
    category: str        # CREATURE | MONSTER
    width: float
    height: float
    health: float
    speed: float
    attack: float
    scale: float
    has_social: bool = False


@dataclass
class ContentPlan:
    entities: list[EntityPlan] = field(default_factory=list)
    machines: list[dict[str, Any]] = field(default_factory=list)
    cables: list[dict[str, Any]] = field(default_factory=list)
    boards: list[dict[str, Any]] = field(default_factory=list)
    keys: list[dict[str, Any]] = field(default_factory=list)
    dimensions: list[dict[str, Any]] = field(default_factory=list)
    configs: list[dict[str, Any]] = field(default_factory=list)
    sounds: list[dict[str, Any]] = field(default_factory=list)
    particles: list[dict[str, Any]] = field(default_factory=list)
    networks: list[dict[str, Any]] = field(default_factory=list)
    fluids: list[dict[str, Any]] = field(default_factory=list)

    @property
    def advanced_entities(self) -> bool:
        return bool(self.entities)

    @property
    def advanced_blocks(self) -> bool:
        return bool(self.machines or self.cables or self.boards)

    @property
    def advanced_fluids(self) -> bool:
        return bool(self.fluids)

    @property
    def any_java(self) -> bool:
        return bool(self.entities or self.machines or self.cables or self.boards or self.keys
                    or self.particles or self.networks or self.fluids)

    @property
    def common_java(self) -> bool:
        return bool(self.configs or self.sounds)


def content_plan(spec: dict[str, Any]) -> ContentPlan:
    nodes = spec["content"]
    dims = [n for n in nodes if n["type"] == "dimension"]
    plan = ContentPlan(dimensions=dims)
    for node in nodes:
        ntype = node["type"]
        nid = _path(node["id"])
        if ntype in ENTITY_NODE_TYPES:
            mechanics = " ".join(node.get("mechanics", [])).lower()
            if ntype == "npc":
                kind = "npc"
            elif ntype == "boss":
                kind = "boss"
            elif "passive" in mechanics or "neutral" in mechanics or "ambient" in mechanics:
                kind = "passive"
            else:
                kind = "hostile"
            cls = _class(node["id"])
            if kind == "npc":
                width, height, health, speed, attack, scale = 0.6, 1.8, 20.0, 0.25, 0.0, 1.0
                category = "CREATURE"
            elif kind == "boss":
                width, height, health, speed, attack, scale = 1.2, 2.8, 240.0, 0.28, 8.0, 1.6
                category = "MONSTER"
            elif kind == "passive":
                width, height, health, speed, attack, scale = 0.7, 1.4, 16.0, 0.22, 0.0, 1.0
                category = "CREATURE"
            else:
                width, height, health, speed, attack, scale = 0.7, 1.9, 30.0, 0.26, 4.0, 1.0
                category = "MONSTER"
            plan.entities.append(EntityPlan(
                node=node, cls=cls, field=_field(node["id"]), kind=kind,
                texture=f"textures/entity/{nid}.png",
                category=category, width=width, height=height,
                health=health, speed=speed, attack=attack, scale=scale,
                has_social=kind == "npc",
            ))
        elif ntype == "machine":
            plan.machines.append(node)
        elif ntype == "energy":
            plan.cables.append(node)
        elif ntype == "config":
            plan.configs.append(node)
        elif ntype == "sound":
            plan.sounds.append(node)
        elif ntype == "particle":
            plan.particles.append(node)
        elif ntype == "network":
            plan.networks.append(node)
        elif ntype == "fluid":
            plan.fluids.append(node)
        elif ntype == "block" and nid.endswith("board"):
            plan.boards.append(node)
        elif ntype in {"key", "item"} and ("key" in nid or "activator" in nid) and dims:
            plan.keys.append(node)
    # A dimension always benefits from a reachable key, even if the spec only
    # generated a generic material. Use the signature artifact when available.
    if dims and not plan.keys:
        candidates = [n for n in nodes if n["type"] in {"artifact", "tool", "item"}]
        if candidates:
            plan.keys.append(candidates[0])
    return plan


