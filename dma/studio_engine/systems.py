def _mechanics_text(node: dict[str, Any]) -> str:
    return " ".join(str(m) for m in node.get("mechanics", []))


def _tool_tier(node: dict[str, Any]) -> str:
    blob = _mechanics_text(node).lower()
    match = re.search(r"durability:\s*(\d+)", blob)
    durability = int(match.group(1)) if match else 0
    if durability >= 1800 or "netherite" in blob or "下界合金" in blob:
        return "NETHERITE"
    if durability >= 800 or "diamond" in blob or "钻石" in blob:
        return "DIAMOND"
    if "stone" in blob or "石" in blob:
        return "STONE"
    return "IRON"


def _tool_kind(node: dict[str, Any]) -> str:
    blob = (node["id"] + " " + _mechanics_text(node)).lower()
    if any(word in blob for word in ("wrench", "rotate", "dismantle", "扳手", "旋转", "拆卸")):
        return "generic"
    if "pickaxe" in blob or "pick" in blob or "镐" in blob:
        return "pickaxe"
    if "shovel" in blob or "spade" in blob or "锹" in blob:
        return "shovel"
    if "hoe" in blob or "锄" in blob:
        return "hoe"
    if "axe" in blob or "斧" in blob:
        return "axe"
    if "sword" in blob or "剑" in blob:
        return "sword"
    return "pickaxe"


def _tool_expr(node: dict[str, Any], mc: str) -> str | None:
    kind = _tool_kind(node)
    if kind == "generic":
        return None
    tier = _tool_tier(node)
    q = "net.minecraft.world.item."
    tier_ref = f"{q}Tiers.{tier}"
    cls = {"sword": "SwordItem", "pickaxe": "PickaxeItem", "axe": "AxeItem",
           "shovel": "ShovelItem", "hoe": "HoeItem"}[kind]
    if _key(mc) >= (1, 20, 5):
        if kind == "sword":
            damage, speed = "3", "-2.4F"
        elif kind == "pickaxe":
            damage, speed = "1.0F", "-2.8F"
        elif kind == "axe":
            damage, speed = "5.0F", "-3.0F"
        elif kind == "shovel":
            damage, speed = "1.5F", "-3.0F"
        else:
            damage, speed = "-3.0F", "0.0F"
        return (f"new {q}{cls}({tier_ref}, new Item.Properties().attributes("
                f"{q}{cls}.createAttributes({tier_ref}, {damage}, {speed})))")
    if kind == "sword":
        args = f"{tier_ref}, 3, -2.4F"
    elif kind == "pickaxe":
        args = f"{tier_ref}, 1, -2.8F"
    elif kind == "axe":
        args = f"{tier_ref}, 5.0F, -3.0F"
    elif kind == "shovel":
        args = f"{tier_ref}, 1.5F, -3.0F"
    else:
        args = f"{tier_ref}, -3, 0.0F"
    return f"new {q}{cls}({args}, new Item.Properties())"


def _armor_slot(node: dict[str, Any]) -> str:
    blob = (node["id"] + " " + _mechanics_text(node)).lower()
    if "leggings" in blob or "legs" in blob or "护腿" in blob:
        return "LEGGINGS"
    if "boots" in blob or "靴" in blob:
        return "BOOTS"
    if "helmet" in blob or "头盔" in blob or "帽子" in blob:
        return "HELMET"
    return "CHESTPLATE"


def _armor_material(node: dict[str, Any], mc: str) -> str:
    blob = _mechanics_text(node).lower()
    if "netherite" in blob or "下界合金" in blob:
        return "NETHERITE"
    if "leather" in blob or "皮革" in blob:
        return "LEATHER"
    if "chain" in blob or "锁链" in blob:
        return "CHAIN" if _key(mc) >= (1, 20, 5) else "CHAINMAIL"
    if "gold" in blob or "金" in blob:
        return "GOLD"
    if "iron" in blob or "铁" in blob:
        return "IRON"
    return "DIAMOND"


def _armor_expr(node: dict[str, Any], mc: str) -> str | None:
    q = "net.minecraft.world.item."
    material = _armor_material(node, mc)
    slot = _armor_slot(node)
    return (f"new {q}ArmorItem({q}ArmorMaterials.{material}, "
            f"{q}ArmorItem.Type.{slot}, new Item.Properties())")


def _food_value(node: dict[str, Any], key: str, default: float) -> float:
    match = re.search(rf"{key}:\s*([0-9.]+)", _mechanics_text(node), re.IGNORECASE)
    return float(match.group(1)) if match else default


def _food_expr(node: dict[str, Any], mc: str) -> str | None:
    q = "net.minecraft.world.item."
    food = "net.minecraft.world.food.FoodProperties"
    nutrition = int(_food_value(node, "nutrition", 4))
    saturation = _food_value(node, "saturation", 0.3)
    builder = (f"new {food}.Builder().nutrition({nutrition})"
               + (f".saturationModifier({saturation}F)" if _key(mc) >= (1, 21, 0)
                  else f".saturationMod({saturation}F)"))
    match = re.search(r"effect:\s*([a-zA-Z_ ]+?)\s+(\d+)\s*(?:s|秒)",
                      _mechanics_text(node), re.IGNORECASE)
    if match:
        effect = _EFFECT_NAMES.get(match.group(1).strip().lower())
        if effect:
            duration = int(match.group(2)) * 20
            instance = (f"new net.minecraft.world.effect.MobEffectInstance("
                        f"net.minecraft.world.effect.MobEffects.{effect}, {duration}, 0)")
            # 1.20.5+ 的 Builder#effect 接收 MobEffectInstance 本体；旧版本接收 Supplier。
            if _key(mc) >= (1, 20, 5):
                builder += f".effect({instance}, 1.0F)"
            else:
                builder += f".effect(() -> {instance}, 1.0F)"
    return f"new {q}Item(new Item.Properties().food({builder}.build()))"


def item_expr(node: dict[str, Any], plan: ContentPlan, loader: str = "", mc: str = "") -> str | None:
    # 1.21.2+ requires Item.Properties#setId and the advanced classes are
    # deliberately skipped there, so the plain item registration must be kept.
    if mc and _key(mc) >= (1, 21, 2):
        return None
    if node in plan.keys:
        return "new RealmKeyItem(new Item.Properties())"
    ntype = node.get("type", "")
    if ntype in {"tool", "weapon"}:
        return _tool_expr(node, mc)
    if ntype == "armor":
        return _armor_expr(node, mc)
    if ntype == "food":
        return _food_expr(node, mc)
    return None


def spawn_egg_lines(plan: ContentPlan, profile, loader: str) -> list[str]:
    """Field declarations + registration expressions for entity spawn eggs."""
    if not plan.entities:
        return []
    if _key(profile.mc) >= (1, 21, 2):
        return []
    lines: list[str] = []
    for entity in plan.entities:
        if loader == "fabric":
            lines.append(
                f'    public static final Item {entity.field}_SPAWN_EGG = registerSpawnEgg('
                f'"{_path(entity.node["id"])}_spawn_egg", ModEntities.{entity.field}, 0x4a3b2a, 0xd7b46a);')
        elif loader == "neoforge":
            lines.append(
                f'    public static final DeferredHolder<Item, Item> {entity.field}_SPAWN_EGG = ITEMS.register('
                f'"{_path(entity.node["id"])}_spawn_egg", () -> new DeferredSpawnEggItem('
                f'ModEntities.{entity.field}, 0x4a3b2a, 0xd7b46a, new Item.Properties()));')
        else:
            lines.append(
                f'    public static final RegistryObject<Item> {entity.field}_SPAWN_EGG = ITEMS.register('
                f'"{_path(entity.node["id"])}_spawn_egg", () -> new ForgeSpawnEggItem('
                f'ModEntities.{entity.field}, 0x4a3b2a, 0xd7b46a, new Item.Properties()));')
    return lines


def spawn_egg_register_args(plan: ContentPlan, profile, loader: str) -> list[str]:
    if _key(profile.mc) >= (1, 21, 2):
        return []
    return [f"{entity.field}_SPAWN_EGG" for entity in plan.entities]


def main_register_lines(plan: ContentPlan, loader: str) -> list[str]:
    lines: list[str] = []
    if plan.advanced_blocks:
        lines.append("        ModContent.register(bus);" if loader != "fabric" else "        ModContent.register();")
    if plan.advanced_entities:
        lines.append("        ModEntities.register(bus);" if loader != "fabric" else "        ModEntities.register();")
    return lines


def needs_client(plan: ContentPlan) -> bool:
    return plan.advanced_entities or bool(plan.machines) or bool(plan.particles)


def fabric_client_entrypoint(plan: ContentPlan) -> str | None:
    if not needs_client(plan):
        return None
    return "client.ClientSetup"


