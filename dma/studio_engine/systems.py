def write_sources(base: Path, ident: dict[str, Any], profile, loader: str) -> dict[str, Any]:
    """Write advanced sources. Returns a manifest with what was generated."""
    spec = ident.get("_spec") or {}
    plan = content_plan(spec)
    modid = ident["modid"]
    package = ident["package"]
    content = base / "content"
    client = base / "client"
    manifest: dict[str, Any] = {"entities": [], "machines": [], "menus": 0,
                                "renderers": [], "energy": [], "config": False,
                                "sounds": [], "particles": [], "network": False,
                                "fluids": [], "skipped": ""}
    if plan.configs:
        write_text(base / "Config.java", _config_java(package, modid, loader))
        manifest["config"] = True
    if plan.sounds:
        write_text(base / "ModSounds.java", _mod_sounds(package, profile, loader))
        manifest["sounds"] = ["ui_click", "machine_hum", "boss_roar"]
    if not plan.any_java:
        return manifest
    if _key(profile.mc) >= (1, 21, 2):
        manifest["skipped"] = (
            f"{profile.mc} 的实体/方块实体/粒子/网络/流体 API 尚未取证；已跳过这些高级 Java，"
            "配置、音效、数据包世界生成与社交系统仍然有效。"
        )
        return manifest
    if loader == "fabric":
        # The generated entity/renderer code targets Mojang mappings and uses
        # Fabric API registries. Yarn names and a missing Fabric API would both
        # turn a working data-pack mod into a compile error.
        if not getattr(profile, "fabric_api", ""):
            manifest["skipped"] = "Fabric 高级 Java 需要 fabric-api 依赖；已跳过实体/机器代码。"
            return manifest
        if (getattr(profile, "mappings", "") or "official") not in {"", "official"}:
            manifest["skipped"] = "Fabric 高级 Java 目前只支持 official(Mojang) 映射；已跳过。"
            return manifest

    if plan.particles:
        write_text(base / "ModParticles.java", _mod_particles(package, plan, profile, loader))
        manifest["particles"] = [n["id"] for n in plan.particles]
    if plan.networks:
        write_text(base / "ModNetwork.java", _mod_network(package, plan, profile, loader))
        manifest["network"] = True
    if plan.fluids:
        if loader in {"forge", "neoforge"}:
            write_text(base / "ModFluids.java", _mod_fluids(package, plan, profile, loader))
            manifest["fluids"] = [n["id"] for n in plan.fluids]
        else:
            manifest["skipped"] = (manifest["skipped"] + " " if manifest["skipped"] else "") + (
                "Fabric 自定义流体尚未取证；已跳过流体 Java，仅保留资源与节点描述。")

    if plan.entities:
        content.mkdir(parents=True, exist_ok=True)
        write_text(base / "ModEntities.java", _mod_entities(package, modid, plan, profile, loader))
        for entity in plan.entities:
            if entity.kind == "npc":
                code = _npc_entity(package, entity, modid)
            elif entity.kind == "boss":
                code = _boss_entity(package, entity, modid)
            else:
                code = _mob_entity(package, entity)
            write_text(content / f"{entity.cls}.java", code)
            manifest["entities"].append({"id": entity.node["id"], "class": entity.cls, "kind": entity.kind})
        manifest["renderers"] = [e.field for e in plan.entities]

    if plan.machines or plan.cables:
        content.mkdir(parents=True, exist_ok=True)
        write_text(content / "EnergyStorage.java", _energy_storage(package))
    if plan.machines:
        write_text(content / "SimpleMachineBlock.java", _machine_block(package, profile.mc))
        write_text(content / "SimpleMachineBlockEntity.java", _simple_machine_be(package, modid, profile.mc, loader))
        write_text(content / "SimpleMachineMenu.java", _simple_machine_menu(package, modid, loader))
        manifest["machines"] = [n["id"] for n in plan.machines]
        manifest["menus"] = 1
        if needs_client(plan):
            client.mkdir(parents=True, exist_ok=True)
            write_text(client / "MachineScreen.java", _machine_screen(package, profile.mc))
    if plan.cables:
        write_text(content / "EnergyCableBlock.java", _energy_cable_block(package, profile.mc))
        write_text(content / "EnergyCableBlockEntity.java", _energy_cable_be(package, profile.mc, loader))
        manifest["energy"] = [n["id"] for n in plan.cables]
    if plan.machines or plan.cables:
        write_text(base / "ModContent.java", _mod_content(package, plan, profile, loader))

    if plan.boards:
        content.mkdir(parents=True, exist_ok=True)
        write_text(content / "QuestBoardBlock.java", _quest_board_block(package, modid, profile.mc))

    if plan.keys:
        content.mkdir(parents=True, exist_ok=True)
        dimension = _path(plan.dimensions[0]["id"])
        write_text(content / "RealmKeyItem.java", _realm_key_item(package, modid, dimension, profile.mc))
        manifest["key"] = plan.keys[0]["id"]

    if needs_client(plan):
        client.mkdir(parents=True, exist_ok=True)
        if plan.entities:
            write_text(client / "NpcRenderer.java", _npc_renderer(package, profile.mc))
            if any(e.kind == "boss" for e in plan.entities):
                write_text(client / "BossRenderer.java", _boss_renderer(package, profile.mc))
        write_text(client / "ClientSetup.java", _client_setup(package, plan, modid, profile.mc, loader))

    return manifest
