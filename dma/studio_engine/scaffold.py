"""Project scaffolding.

Strategy:
1. For Forge/NeoForge, download the exact official MDK for the resolved
   (Minecraft, loader) pair. This is the only reliable way to support the whole
   version range, because mappings, Gradle plugins and metadata format change
   constantly.
2. If the MDK cannot be fetched, fall back to a parameterised bundled template.
3. For Fabric, Loom's build file is stable enough to parameterise directly.

Generated Java is intentionally conservative: registrations use the most stable
API surface for each loader. Behaviour that changes between versions is generated
as a separate slice with a TODO and an API-card reference instead of guessed.
"""
