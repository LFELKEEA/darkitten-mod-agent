def _pkg_path(package: str) -> str:
    return package.replace(".", "/")


def _java_name(node_id: str) -> str:
    name = node_id.split(":", 1)[-1]
    name = re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_")
    if not name:
        name = "entry"
    if name[0].isdigit():
        name = "_" + name
    return name.upper()


def _escape_java(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def _node_path(node: dict[str, Any]) -> str:
    return node["id"].split(":", 1)[-1]


def _is_modern(mc: str) -> bool:
    return mc.startswith("26.") or _ver_key(mc) >= _ver_key("1.21")


def _needs_item_id(mc: str) -> bool:
    """1.21.2+ requires Item.Properties/BlockBehaviour.Properties to carry an id."""
    return mc.startswith("26.") or _ver_key(mc) >= _ver_key("1.21.2")


def _id_class(mc: str) -> str:
    """Minecraft 26.x unobfuscated jars renamed ResourceLocation to Identifier."""
    return "Identifier" if mc.startswith("26.") else "ResourceLocation"


def _fabric_tab_api(mc: str) -> str:
    """Fabric API renamed fabric-itemgroup-api-v1 to fabric-creative-tab-api-v1 in 26.x."""
    if mc.startswith("26."):
        return "net.fabricmc.fabric.api.creativetab.v1.FabricCreativeModeTab"
    return "net.fabricmc.fabric.api.itemgroup.v1.FabricItemGroup"


def _ver_key(v: str) -> tuple:
    out = []
    for part in re.split(r"[.\-+]", v):
        m = re.match(r"(\d+)", part)
        out.append((0, int(m.group(1))) if m else (1, part))
    return tuple(out)


def _block_class(node: dict[str, Any]) -> str:
    """Java class that backs a node's block expression."""
    if node["type"] == "machine":
        return "SimpleMachineBlock"
    if node["type"] == "energy":
        return "EnergyCableBlock"
    return "QuestBoardBlock"


def _block_types() -> set[str]:
    return assets.BLOCK_TYPES


def _item_types() -> set[str]:
    return assets.ITEM_TYPES


