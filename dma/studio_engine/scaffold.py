def _write_metadata(project: Path, spec: dict[str, Any], profile: VersionProfile) -> None:
    ident = spec["identity"]
    meta_dir = project / "src" / "main" / "resources" / "META-INF"
    meta_dir.mkdir(parents=True, exist_ok=True)

    if profile.loader == "fabric":
        plan = systems.content_plan(spec)
        entrypoints: dict[str, list[str]] = {
            "main": [f"{ident['package']}.{_class_name(ident['modid'])}"],
        }
        if _advanced_java(profile, plan):
            client_entry = systems.fabric_client_entrypoint(plan)
            if client_entry:
                entrypoints["client"] = [f"{ident['package']}.{client_entry}"]
        write_json(project / "src" / "main" / "resources" / "fabric.mod.json", {
            "schemaVersion": 1,
            "id": ident["modid"],
            "version": ident["version"],
            "name": ident["name_en"],
            "description": ident["description_en"],
            "authors": [ident["author"]],
            "license": ident["license"],
            "environment": "*",
            "entrypoints": entrypoints,
            "depends": {
                "fabricloader": f">={profile.loader_version}",
                "minecraft": f">={profile.mc}",
                "java": f">={profile.java_major}",
                **({"fabric-api": "*"} if profile.fabric_api else {}),
            },
            "mixins": [],
        })
        return

    is_neoforge = profile.loader == "neoforge"
    toml_name = "neoforge.mods.toml" if is_neoforge and _is_modern(profile.mc) else "mods.toml"
    loader_key = "neoforge" if is_neoforge else "forge"
    if is_neoforge:
        # loaderVersion is the FML language-provider version, not the NeoForge
        # artifact version: 21.1 ships FML 4.x, 26.x ships 5.x, etc. "[1,)"
        # accepts every published NeoForge loader.
        loader_range = "[1,)"
        dep_range = f"[{profile.loader_version},)"
    else:
        # Forge's language provider reports its major only ("47"), while the
        # artifact version is "47.4.5"; a range starting at 47.4.5 is rejected
        # with "needs language provider javafml:47.4.5 ... We have found 47".
        loader_version = profile.loader_version.split("-")[-1]
        major = loader_version.split(".")[0] if loader_version else ""
        loader_range = dep_range = f"[{major},)" if major else "[1,)"
    # Forge before 1.20.5 rejects dependency entries without `mandatory`;
    # the `type` field only exists from 1.20.5 / NeoForge onward.
    legacy_mandatory = not is_neoforge and _ver_key(profile.mc) < _ver_key("1.20.5")
    dep_line = '    mandatory=true' if legacy_mandatory else '    type="required"'
    text = f'''modLoader="javafml"
loaderVersion="{loader_range}"
license="{ident['license']}"
issueTrackerURL="https://example.com/issues"

[[mods]]
modId="{ident['modid']}"
version="{ident['version']}"
displayName="{ident['name_en']}"
authors="{ident['author']}"
description=''' + "'''" + f"{ident['description_en']}" + "'''" + f'''

[[dependencies.{ident['modid']}]]
    modId="minecraft"
{dep_line}
    versionRange="[{profile.mc},)"
    ordering="NONE"
    side="BOTH"

[[dependencies.{ident['modid']}]]
    modId="{loader_key}"
{dep_line}
    versionRange="{dep_range}"
    ordering="NONE"
    side="BOTH"
'''
    write_text(meta_dir / toml_name, text)


