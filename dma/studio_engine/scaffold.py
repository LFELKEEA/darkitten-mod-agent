def _class_name(modid: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", modid)
    return "".join(p.capitalize() for p in parts if p) or "ExampleMod"


def _write_sources(project: Path, spec: dict[str, Any], profile: VersionProfile) -> dict[str, Any]:
    ident = dict(spec["identity"])
    ident["_spec"] = spec
    package = ident["package"]
    base = project / "src" / "main" / "java" / _pkg_path(package)
    base.mkdir(parents=True, exist_ok=True)
    main_class = _class_name(ident["modid"])

    if profile.loader == "fabric":
        _write_fabric_sources(base, ident, profile, main_class)
    elif profile.loader == "neoforge":
        _write_neoforge_sources(base, ident, profile, main_class)
    else:
        _write_forge_sources(base, ident, profile, main_class)
    return systems.write_sources(base, ident, profile, profile.loader)


