def _fabric_is_mojmap(profile: VersionProfile) -> bool:
    return (profile.mappings or "official") in {"", "official"}


def _advanced_java(profile: VersionProfile, plan) -> bool:
    """True when systems.py will actually emit advanced Java for this profile."""
    if systems._key(profile.mc) >= (1, 21, 2):
        return False
    if profile.loader == "fabric" and (
        not getattr(profile, "fabric_api", "") or not _fabric_is_mojmap(profile)
    ):
        return False
    return plan.any_java


