# SJTUG/ZJU serve the full BMCLAPI tree including the neoform zips; the NYIST
# mirror answers 200 on HEAD but Cloudflare rejects the actual zip download.
MIRROR_NEOFORGE = "https://mirrors.zju.edu.cn/bmclapi/"
MIRROR_NEOFORGE_2 = "https://mirror4.nyist.edu.cn/bmclapi/"
MIRROR_NEOFORGE_3 = "https://mirror.minguncle.cn/maven/"
# ZJU serves the complete BMCLAPI maven tree (ForgeGradle plugin, mcp_config,
# userdev, MCP data). The minguncle host is kept as a fallback but is often
# throttled to a few KB/s for small metadata files.
MIRROR_FORGE = "https://mirrors.zju.edu.cn/bmclapi/"
MIRROR_FORGE_2 = "https://mirror.minguncle.cn/maven.minecraftforge.net/"
MIRROR_FORGE_3 = "https://bmclapi2.bangbang93.com/maven/"
MAVEN_FABRIC = "https://maven.fabricmc.net/"
MIRROR_FABRIC = "https://repository.hanbings.io/proxy/"
MAVEN_NEOFORGE = "https://maven.neoforged.net/releases/"
MAVEN_FORGE = "https://maven.minecraftforge.net/"


def _repo_lines(loader: str, indent: str = "    ", *, plugin: bool = False) -> list[str]:
    """Repository list ordered so reachable hosts are tried first.

    maven.neoforged.net and maven.minecraftforge.net are frequently either
    blocked or mapped to a local TLS interceptor; the public mirrors are tried
    before the official hosts so a broken certificate cannot abort resolution.
    Plugin resolution skips the official hosts entirely: Gradle aborts plugin
    lookup when one repository is unreachable, and the plugin markers live on
    the public mirrors / Gradle Plugin Portal.
    """
    lines = [f"{indent}mavenCentral()"]
    if loader == "fabric":
        lines.append(f"{indent}maven {{ url = '{MIRROR_FABRIC}' }}")
        lines.append(f"{indent}maven {{ url = '{MAVEN_FABRIC}' }}")
    elif loader == "neoforge":
        lines.append(f"{indent}maven {{ url = '{MIRROR_NEOFORGE}' }}")
        lines.append(f"{indent}maven {{ url = '{MIRROR_NEOFORGE_2}' }}")
        lines.append(f"{indent}maven {{ url = '{MIRROR_NEOFORGE_3}' }}")
        if not plugin:
            lines.append(f"{indent}maven {{ url = '{MAVEN_NEOFORGE}' }}")
    elif loader == "forge":
        lines.append(f"{indent}maven {{ url = '{MIRROR_FORGE}' }}")
        lines.append(f"{indent}maven {{ url = '{MIRROR_FORGE_2}' }}")
        lines.append(f"{indent}maven {{ url = '{MIRROR_FORGE_3}' }}")
        if not plugin:
            lines.append(f"{indent}maven {{ url = '{MAVEN_FORGE}' }}")
    lines.append(f"{indent}gradlePluginPortal()")
    return lines


def _repos_block(loader: str, indent: str = "    ", *, plugin: bool = False) -> str:
    return "\n".join(_repo_lines(loader, indent, plugin=plugin))


def _scaffold_from_template(project: Path, spec: dict[str, Any], profile: VersionProfile) -> None:
    ident = spec["identity"]
    if profile.loader == "fabric":
        _write_fabric_build(project, spec, profile)
    elif profile.loader == "neoforge":
        _write_neoforge_build(project, spec, profile)
    elif profile.loader == "forge":
        _write_forge_build(project, spec, profile)
    else:
        raise McmodError(f"不支持的加载器：{profile.loader}")
    plugin_repos = _repos_block(profile.loader, "        ", plugin=True)
    strategy = ""
    if profile.loader == "fabric" and (
        profile.mc.startswith("26.") or _ver_key(profile.mc) >= _ver_key("26.1")
    ):
        # The no-remap plugin id has no marker on Maven; map it to the module.
        strategy = (
            "    resolutionStrategy {\n"
            "        eachPlugin {\n"
            "            if (requested.id.id == 'net.fabricmc.fabric-loom') {\n"
            "                useModule(\"net.fabricmc:fabric-loom:${requested.version}\")\n"
            "            }\n"
            "        }\n"
            "    }\n"
        )
    write_text(project / "settings.gradle", (
        "pluginManagement {\n"
        "    repositories {\n"
        f"{plugin_repos}\n"
        "    }\n"
        f"{strategy}"
        "}\n"
        f"rootProject.name = '{ident['modid']}'\n"
    ))


def _write_fabric_build(project: Path, spec: dict[str, Any], profile: VersionProfile) -> None:
    ident = spec["identity"]
    loom = profile.loom or "1.19.3"
    # Minecraft 26.1+ ships unobfuscated jars: use the no-remap Loom plugin,
    # skip mapping declaration, and depend on mods through plain configurations.
    modern = profile.mc.startswith("26.") or _ver_key(profile.mc) >= _ver_key("26.1")
    if modern:
        plugin_id = "net.fabricmc.fabric-loom"
        dep_cfg = "implementation"
        mappings_line = ""
    else:
        plugin_id = "fabric-loom"
        dep_cfg = "modImplementation"
        if profile.mappings in {"", "official"}:
            mappings_line = "    mappings loom.officialMojangMappings()\n"
        else:
            mappings_line = (
                f"    mappings loom.layered {{ mappings \"net.fabricmc:yarn:{profile.mappings}:v2\" }}\n"
            )
    api_dep = f"{dep_cfg} \"net.fabricmc.fabric-api:fabric-api:{profile.fabric_api}\"" if profile.fabric_api else ""
    write_text(project / "gradle.properties", (
        f"org.gradle.jvmargs=-Xmx2G\n"
        f"org.gradle.parallel=true\n"
        f"minecraft_version={profile.mc}\n"
        f"loader_version={profile.loader_version}\n"
        f"loom_version={loom}\n"
        f"fabric_api={profile.fabric_api}\n"
        f"loom_fabric_repository={MIRROR_FABRIC}\n"
        f"mod_version={ident['version']}\n"
        f"maven_group={ident['package'].rsplit('.', 1)[0]}\n"
        f"archives_base_name={ident['modid']}\n"
    ))
    write_text(project / "build.gradle", f"""plugins {{
    id '{plugin_id}' version '{loom}'
    id 'maven-publish'
}}

version = project.mod_version
group = project.maven_group

base {{
    archivesName = project.archives_base_name
}}

repositories {{
{_repos_block('fabric')}
}}

dependencies {{
    minecraft "com.mojang:minecraft:${{project.minecraft_version}}"
{mappings_line}    {dep_cfg} "net.fabricmc:fabric-loader:${{project.loader_version}}"
    {api_dep}
}}

processResources {{
    inputs.property "version", project.version
    filesMatching("fabric.mod.json") {{
        expand "version": project.version
    }}
}}

tasks.withType(JavaCompile).configureEach {{
    it.options.encoding = "UTF-8"
    it.options.release = {profile.java_major}
}}

java {{
    withSourcesJar()
    sourceCompatibility = JavaVersion.toVersion({profile.java_major})
    targetCompatibility = JavaVersion.toVersion({profile.java_major})
}}
""")


def _write_neoforge_build(project: Path, spec: dict[str, Any], profile: VersionProfile) -> None:
    ident = spec["identity"]
    # ModDevGradle is the current official NeoForge build plugin.
    # ModDevGradle 2.x is required from 1.21.2 on. 2.0.147 is the newest
    # release whose artifact Gradle's own mirror serves in full (2.0.148 still
    # redirects to maven.neoforged.net); 1.0.23 remains the 1.20.2-1.21.1 line.
    modern_toolchain = profile.mc.startswith("26.") or _ver_key(profile.mc) >= _ver_key("1.21.2")
    mdg = "2.0.147" if modern_toolchain else "1.0.23"
    # ModDevGradle 1.x defaults to NeoFormRuntime 1.0.5, which several mirrors
    # never synced. 1.0.42 is published, cache-friendly and accepts the same
    # command line, so pin it for the 1.0.x line.
    nfrt = "" if modern_toolchain else "neoForge.neoFormRuntime.version=1.0.42\n"
    write_text(project / "gradle.properties", (
        f"org.gradle.jvmargs=-Xmx3G\n"
        f"org.gradle.parallel=true\n"
        f"{nfrt}"
        f"mod_id={ident['modid']}\n"
        f"mod_name={ident['name_en']}\n"
        f"mod_license={ident['license']}\n"
        f"mod_version={ident['version']}\n"
        f"mod_group_id={ident['package'].rsplit('.', 1)[0]}\n"
        f"mod_authors={ident['author']}\n"
    ))
    write_text(project / "build.gradle", f"""plugins {{
    id 'java'
    id 'net.neoforged.moddev' version '{mdg}'
}}

version = project.mod_version
group = project.mod_group_id

base {{
    archivesName = project.mod_id
}}

// ModDevGradle registers maven.neoforged.net itself, and that host is often
// unreachable (or patched to 127.0.0.1). Rewriting the repository URL after the
// plugin applies also covers the injected repository, which a plain repositories
// block cannot do. Override with -Pneoforge_maven=<url> if the default is down.
def neoforgeMirror = project.findProperty('neoforge_maven') ?: '{MIRROR_NEOFORGE}'
allprojects {{ p ->
    p.repositories.withType(MavenArtifactRepository).configureEach {{ repo ->
        if (repo.url.toString().contains('maven.neoforged.net')) {{
            repo.url = p.uri(neoforgeMirror)
        }}
    }}
}}

repositories {{
    def mcmodLocal = project.findProperty('mcmod_local_repo')
    if (mcmodLocal) {{
        maven {{ url = project.uri(mcmodLocal) }}
    }}
{_repos_block('neoforge')}
}}

java.toolchain.languageVersion = JavaLanguageVersion.of({profile.java_major})

neoForge {{
    version = "{profile.loader_version}"
    runs {{
        client {{
            client()
        }}
        server {{
            server()
        }}
    }}
    mods {{
        "${{project.mod_id}}" {{
            sourceSet sourceSets.main
        }}
    }}
}}

tasks.withType(JavaCompile).configureEach {{
    options.encoding = 'UTF-8'
}}

// Forward console input so an automated `stop` reaches the dedicated server.
tasks.matching {{ it.name == 'runServer' }}.configureEach {{
    standardInput = System.in
}}
""")


def _write_forge_build(project: Path, spec: dict[str, Any], profile: VersionProfile) -> None:
    ident = spec["identity"]
    write_text(project / "gradle.properties", (
        f"org.gradle.jvmargs=-Xmx3G\n"
        # ForgeGradle's MCP steps touch project services from worker threads;
        # parallel project execution makes Gradle close them too early.
        f"org.gradle.parallel=false\n"
        # ForgeGradle probes maven.minecraftforge.net with a HEAD request that
        # has no read timeout; on filtered networks that hangs the build.
        f"systemProp.net.minecraftforge.gradle.check.certs=false\n"
        f"mod_id={ident['modid']}\n"
        f"mod_name={ident['name_en']}\n"
        f"mod_license={ident['license']}\n"
        f"mod_version={ident['version']}\n"
        f"mod_group_id={ident['package'].rsplit('.', 1)[0]}\n"
        f"mod_authors={ident['author']}\n"
    ))
    mapping_line = "official" if _ver_key(profile.mc) >= _ver_key("1.17") else "snapshot"
    java_ver = profile.java_major
    # Forge artifact versions already carry the MC prefix (1.20.1-47.4.5);
    # Fabric/NeoForge style loader-only versions need it prepended.
    lv = profile.loader_version
    forge_dep = lv if lv.startswith(f"{profile.mc}-") else f"{profile.mc}-{lv}"
    write_text(project / "build.gradle", f"""plugins {{
    id 'eclipse'
    id 'idea'
    id 'maven-publish'
    id 'net.minecraftforge.gradle' version '[6.0,6.2)'
}}

version = project.mod_version
group = project.mod_group_id

base {{
    archivesName = project.mod_id
}}

// ForgeGradle also resolves MCP metadata from maven.minecraftforge.net and
// ignores project repositories for some downloads, so rewrite every matching
// repository URL after the plugin has registered them.
def forgeMirror = project.findProperty('forge_maven') ?: '{MIRROR_FORGE}'
allprojects {{ p ->
    p.repositories.withType(MavenArtifactRepository).configureEach {{ repo ->
        if (repo.url.toString().contains('maven.minecraftforge.net')) {{
            repo.url = p.uri(forgeMirror)
        }}
    }}
}}

repositories {{
    def mcmodLocal = project.findProperty('mcmod_local_repo')
    if (mcmodLocal) {{
        maven {{ url = project.uri(mcmodLocal) }}
    }}
{_repos_block('forge')}
}}

java.toolchain.languageVersion = JavaLanguageVersion.of({java_ver})

minecraft {{
    mappings channel: '{mapping_line}', version: '{profile.mc}'
    runs {{
        client {{
            workingDirectory project.file('run')
            property 'forge.logging.markers', 'REGISTRIES'
            property 'forge.logging.console.level', 'debug'
            mods {{ source sourceSets.main }}
        }}
        server {{
            workingDirectory project.file('run')
            property 'forge.logging.markers', 'REGISTRIES'
            property 'forge.logging.console.level', 'debug'
            // Do not put --nogui here: ForgeGradle prepends run args before
            // --launchTarget and FML then fails with "Failed to find system
            // mod: minecraft". The headless flag is passed via --args instead.
            mods {{ source sourceSets.main }}
        }}
    }}
}}

dependencies {{
    minecraft "net.minecraftforge:forge:{forge_dep}"
}}

tasks.withType(JavaCompile).configureEach {{
    options.encoding = 'UTF-8'
}}

tasks.matching {{ it.name == 'runServer' }}.configureEach {{
    standardInput = System.in
}}
""")


