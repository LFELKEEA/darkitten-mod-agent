def _scaffold_from_mdk(project: Path, spec: dict[str, Any], profile: VersionProfile) -> None:
    cache = Path.home() / ".mcmod" / "cache"
    filename = f"{profile.loader}-{profile.loader_version.replace('+', '_')}-mdk.zip"
    zip_path = cache / filename
    mirrors = [profile.mdk_mirror] if profile.mdk_mirror else []
    download(profile.mdk_url, zip_path, timeout=180, mirrors=mirrors)
    with temp_dir("mcmod-mdk-") as tmp:
        unzip(zip_path, tmp)
        roots = [p for p in tmp.iterdir() if p.is_dir()]
        root = roots[0] if len(roots) == 1 and not (tmp / "build.gradle").exists() else tmp
        _copy_tree(root, project)
        # The MDK ships an example mod. Remove it so it cannot collide with ours.
        _remove_example_sources(project)
        _patch_mdk_properties(project, spec, profile)


def _copy_tree(src: Path, dst: Path) -> None:
    for item in src.iterdir():
        if item.name in {".git", "run", "build", ".gradle"}:
            continue
        target = dst / item.name
        if item.is_dir():
            shutil.copytree(item, target, dirs_exist_ok=True)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(item, target)


def _remove_example_sources(project: Path) -> None:
    """Remove only MDK example files, never arbitrary user code."""
    java_root = project / "src" / "main" / "java"
    if java_root.exists():
        for path in list(java_root.rglob("*")):
            if path.is_file() and path.name.lower() in {"examplemod.java", "examplemodclient.java", "examplemoddatagen.java"}:
                try:
                    path.unlink()
                except OSError:
                    pass
        # Remove now-empty example package directories.
        for path in sorted(java_root.rglob("*"), reverse=True):
            if path.is_dir() and not any(path.iterdir()):
                try:
                    path.rmdir()
                except OSError:
                    pass
    for res in [project / "src" / "main" / "resources" / "assets" / "examplemod",
                project / "src" / "main" / "resources" / "data" / "examplemod"]:
        if res.exists():
            shutil.rmtree(res, ignore_errors=True)


def _patch_mdk_properties(project: Path, spec: dict[str, Any], profile: VersionProfile) -> None:
    ident = spec["identity"]
    props = project / "gradle.properties"
    values = {
        "mod_id": ident["modid"],
        "mod_name": ident["name_en"],
        "mod_license": ident["license"],
        "mod_version": ident["version"],
        "mod_group_id": ident["package"].rsplit(".", 1)[0] if "." in ident["package"] else "com.example",
        "mod_authors": ident["author"],
        "mod_description": ident["description_en"].replace("\n", " "),
    }
    if props.exists():
        text = props.read_text(encoding="utf-8", errors="replace")
        for key, value in values.items():
            pattern = re.compile(rf"^{re.escape(key)}\s*=.*$", re.MULTILINE)
            if pattern.search(text):
                text = pattern.sub(f"{key}={value}", text)
            else:
                text += f"\n{key}={value}\n"
        props.write_text(text, encoding="utf-8", newline="\n")
    else:
        write_text(props, "\n".join(f"{k}={v}" for k, v in values.items()) + "\n")

    settings = project / "settings.gradle"
    if settings.exists():
        text = settings.read_text(encoding="utf-8", errors="replace")
        text = re.sub(r"rootProject\.name\s*=\s*['\"][^'\"]+['\"]",
                      f"rootProject.name = '{ident['modid']}'", text)
        settings.write_text(text, encoding="utf-8", newline="\n")

    # Some MDKs keep the group in build.gradle.
    build = project / "build.gradle"
    if build.exists():
        text = build.read_text(encoding="utf-8", errors="replace")
        text = re.sub(r"group\s*=\s*['\"][^'\"]+['\"]",
                      f"group = '{values['mod_group_id']}'", text, count=1)
        build.write_text(text, encoding="utf-8", newline="\n")


