def scaffold(
    project: Path,
    spec: dict[str, Any],
    profile: VersionProfile,
    *,
    use_mdk: bool = True,
    force: bool = False,
) -> dict[str, Any]:
    project = project.resolve()
    if project.exists() and any(project.iterdir()) and not force:
        raise McmodError(f"目录非空：{project}（加 --force 覆盖生成文件，或换一个目录）")
    ensure_dir(project)
    mode = "template"
    warnings: list[str] = []

    if profile.loader in {"forge", "neoforge"} and use_mdk and profile.mdk_url:
        try:
            _scaffold_from_mdk(project, spec, profile)
            mode = "mdk"
        except Exception as exc:  # noqa: BLE001 - fall back intentionally
            warnings.append(f"MDK 拉取/应用失败，回退内置模板：{exc}")
            _scaffold_from_template(project, spec, profile)
    else:
        _scaffold_from_template(project, spec, profile)

    _write_common(project, spec, profile)
    _write_metadata(project, spec, profile)
    advanced = _write_sources(project, spec, profile)
    generated = assets.generate_assets(project, spec, profile.mc, profile.loader)
    from . import social, worldgen
    generated["worldgen"] = worldgen.generate_worldgen(project, spec, profile.mc, profile.loader)
    generated["social"] = social.generate_social(project, spec, profile.mc, profile.loader)
    generated["advanced"] = advanced
    if advanced.get("skipped"):
        warnings.append(advanced["skipped"])
    _write_todos(project, spec, profile)
    write_json(project / ".mcmod" / "state.json", {
        "schema": "mcmod-state/1",
        "created_at": now_iso(),
        "mode": mode,
        "profile": profile.to_dict(),
        "stage": "scaffolded",
        "warnings": warnings,
        "asset_stats": generated,
        "next": ["audit", "build", "verify"],
    })
    return {"mode": mode, "warnings": warnings, "assets": generated}


