def add_slice(project: Path, node_type: str, node_id: str, name_zh: str = "", name_en: str = "") -> dict[str, Any]:
    """Add a content node to the spec and regenerate sources/assets."""
    spec = read_json(project / "mod-spec.json")
    if not spec:
        raise McmodError("找不到 mod-spec.json")
    modid = spec["identity"]["modid"]
    full_id = node_id if ":" in node_id else f"{modid}:{slug(node_id)}"
    if any(n["id"] == full_id for n in spec["content"]):
        raise McmodError(f"内容已存在：{full_id}")
    from .spec import _node, TYPE_LABEL_ZH
    zh = name_zh or full_id.split(":", 1)[1].replace("_", " ").title()
    en = name_en or full_id.split(":", 1)[1].replace("_", " ").title()
    node = _node(modid, full_id.split(":", 1)[1], node_type, zh, en,
                 TYPE_LABEL_ZH.get(node_type, node_type), "由 slice 命令添加。", 2)
    spec["content"].append(node.to_dict())
    write_json(project / "mod-spec.json", spec)
    state = read_json(project / ".mcmod" / "state.json", {}) or {}
    profile_data = state.get("profile", {})
    profile = VersionProfile(**profile_data) if profile_data else None
    if profile is None:
        raise McmodError("缺少 .mcmod/state.json 中的版本信息")
    # Add a synthetic spec field used by the generators.
    spec["_spec"] = spec
    advanced = _write_sources(project, spec, profile)
    assets.generate_assets(project, spec, profile.mc, profile.loader)
    from . import social, worldgen
    worldgen.generate_worldgen(project, spec, profile.mc, profile.loader)
    social.generate_social(project, spec, profile.mc, profile.loader)
    from .spec import spec_to_markdown
    write_text(project / "GDD.md", spec_to_markdown(spec))
    state = read_json(project / ".mcmod" / "state.json", {}) or {}
    stats = state.get("asset_stats") or {}
    stats["advanced"] = advanced
    state["asset_stats"] = stats
    write_json(project / ".mcmod" / "state.json", state)
    return node.to_dict()
