"""Trusted asset library: validated first, experimental opt-in (P1-07).

The product must not redistribute vanilla Minecraft assets.  The library
therefore ships *synthetic* trusted shapes (cube, cross, slab, stairs, pane)
generated by :mod:`blockbench`, plus an experimental area for assets the user
imports.  Cloning supports resize / texture swap / rotation without touching
UVs by hand.
"""

from __future__ import annotations

import json
import shutil
from dataclasses import dataclass
from pathlib import Path

from . import blockbench

VALIDATED = "validated"
EXPERIMENTAL = "experimental"


@dataclass
class AssetEntry:
    name: str
    kind: str
    path: str
    validated: bool
    description: str = ""

    def to_dict(self) -> dict:
        return {
            "name": self.name,
            "kind": self.kind,
            "path": self.path,
            "validated": self.validated,
            "description": self.description,
        }


class AssetLibrary:
    def __init__(self, root: Path):
        self.root = Path(root)
        self.base = self.root / ".dma" / "assets"
        self.dirs = {
            VALIDATED: self.base / VALIDATED,
            EXPERIMENTAL: self.base / EXPERIMENTAL,
        }

    # ------------------------------------------------------------------
    def bootstrap(self) -> list[AssetEntry]:
        """Create the built-in validated shapes if they are missing."""
        self.dirs[VALIDATED].mkdir(parents=True, exist_ok=True)
        self.dirs[EXPERIMENTAL].mkdir(parents=True, exist_ok=True)
        builders = {
            "cube": lambda: blockbench.full_block("cube"),
            "cross": lambda: blockbench.cross_model("cross"),
            "slab": lambda: _slab(),
            "stairs": lambda: _stairs(),
            "pane": lambda: _pane(),
        }
        written: list[AssetEntry] = []
        for name, build in builders.items():
            target = self.dirs[VALIDATED] / f"{name}.bbmodel"
            if target.exists():
                continue
            blockbench.save_bbmodel(build(), target)
            written.append(
                AssetEntry(name, "bbmodel", target.relative_to(self.root).as_posix(), True)
            )
        return written

    def list(self, *, validated_only: bool = True) -> list[AssetEntry]:
        rows: list[AssetEntry] = []
        for bucket, path in self.dirs.items():
            if validated_only and bucket != VALIDATED:
                continue
            if not path.is_dir():
                continue
            for item in sorted(path.iterdir()):
                if item.is_file():
                    rows.append(
                        AssetEntry(
                            item.stem,
                            item.suffix.lstrip("."),
                            item.relative_to(self.root).as_posix(),
                            bucket == VALIDATED,
                        )
                    )
        return rows

    def resolve(self, name: str, *, validated_only: bool = True) -> Path | None:
        for bucket in (VALIDATED, EXPERIMENTAL):
            if validated_only and bucket != VALIDATED:
                continue
            target = self.dirs[bucket] / name
            if target.is_file():
                return target
            for suffix in (".bbmodel", ".json", ".png"):
                candidate = self.dirs[bucket] / f"{name}{suffix}"
                if candidate.is_file():
                    return candidate
        return None

    # ------------------------------------------------------------------
    def clone(
        self,
        name: str,
        dest: Path,
        *,
        texture: str | None = None,
        scale: float = 1.0,
        rotation: tuple[float, float, float] | None = None,
        offset: tuple[float, float, float] | None = None,
    ) -> dict:
        source = self.resolve(name)
        if source is None:
            raise FileNotFoundError(f"资产库中没有已验证模板：{name}")
        dest = Path(dest)
        if source.suffix == ".bbmodel" and dest.suffix.lower() != ".bbmodel":
            dest = dest.with_suffix(".bbmodel")
        if source.suffix == ".bbmodel":
            model = blockbench.load_bbmodel(source)
            model = _transform(model, scale=scale, rotation=rotation, offset=offset)
            if texture:
                model.texture_name = texture
            blockbench.save_bbmodel(model, dest)
            return {
                "source": source.relative_to(self.root).as_posix(),
                "dest": str(dest),
                "cubes": len(model.cubes),
                "scale": scale,
                "texture": model.texture_name,
            }
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, dest)
        return {"source": source.relative_to(self.root).as_posix(), "dest": str(dest), "copied": True}

    def import_asset(self, source: Path, *, validated: bool = False) -> AssetEntry:
        source = Path(source)
        if not source.is_file():
            raise FileNotFoundError(source)
        bucket = VALIDATED if validated else EXPERIMENTAL
        target = self.dirs[bucket] / source.name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, target)
        style = "validated" if validated else "experimental"
        meta = self.base / f"{source.stem}.source.json"
        meta.write_text(
            json.dumps(
                {"source": source.name, "bucket": style, "license": "user-provided"},
                ensure_ascii=False,
                indent=2,
            ),
            encoding="utf-8",
        )
        if not validated:
            issues = self._validate(target)
            meta.write_text(
                json.dumps(
                    {"source": source.name, "bucket": style, "issues": issues},
                    ensure_ascii=False,
                    indent=2,
                ),
                encoding="utf-8",
            )
        return AssetEntry(source.stem, source.suffix.lstrip("."), target.relative_to(self.root).as_posix(), validated)

    def promote(self, name: str) -> AssetEntry:
        source = self.resolve(name, validated_only=False)
        if source is None:
            raise FileNotFoundError(name)
        if source.parent == self.dirs[VALIDATED]:
            return AssetEntry(source.stem, source.suffix.lstrip("."), source.relative_to(self.root).as_posix(), True)
        issues = self._validate(source)
        if issues:
            raise ValueError("未通过校验，不能提升：" + "；".join(issues))
        target = self.dirs[VALIDATED] / source.name
        shutil.move(str(source), target)
        return AssetEntry(source.stem, source.suffix.lstrip("."), target.relative_to(self.root).as_posix(), True)

    def summary(self) -> dict:
        rows = self.list(validated_only=False)
        return {
            "root": str(self.base),
            "validated": [item.to_dict() for item in rows if item.validated],
            "experimental": [item.to_dict() for item in rows if not item.validated],
        }

    # ------------------------------------------------------------------
    def _validate(self, path: Path) -> list[str]:
        if path.suffix != ".bbmodel":
            return []
        try:
            model = blockbench.load_bbmodel(path)
        except Exception as exc:  # noqa: BLE001 - 坏文件按错误返回
            return [f"无法解析：{exc}"]
        return blockbench.validate(model)


# ----------------------------------------------------------------------
def _transform(
    model: blockbench.BlockbenchModel,
    *,
    scale: float,
    rotation: tuple[float, float, float] | None,
    offset: tuple[float, float, float] | None,
) -> blockbench.BlockbenchModel:
    scale = max(0.05, float(scale or 1.0))
    for item in model.cubes:
        item.from_ = tuple(round(value * scale, 3) for value in item.from_)
        item.to = tuple(round(value * scale, 3) for value in item.to)
        if offset:
            item.from_ = tuple(round(value + shift, 3) for value, shift in zip(item.from_, offset))
            item.to = tuple(round(value + shift, 3) for value, shift in zip(item.to, offset))
        if rotation:
            item.rotation = tuple(float(value) for value in rotation)
            item.origin = tuple(
                round((low + high) / 2, 3) for low, high in zip(item.from_, item.to)
            )
    return model


def _slab() -> blockbench.BlockbenchModel:
    return blockbench.create_bbmodel(
        "slab", [blockbench.cube("slab", (0, 0, 0), (16, 8, 16))]
    )


def _stairs() -> blockbench.BlockbenchModel:
    return blockbench.create_bbmodel(
        "stairs",
        [
            blockbench.cube("base", (0, 0, 0), (16, 8, 16)),
            blockbench.cube("step", (0, 8, 8), (16, 16, 16)),
        ],
    )


def _pane() -> blockbench.BlockbenchModel:
    return blockbench.create_bbmodel(
        "pane", [blockbench.cube("pane", (7, 0, 0), (9, 16, 16))]
    )
